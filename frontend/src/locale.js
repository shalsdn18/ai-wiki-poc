export const t = (key) => messages[key] ?? key
export const categoryLabel = (category) => categories[category] ?? category

export function apiErrorMessage(detail, status) {
  if (typeof detail === 'string' && apiErrors[detail]) return t(apiErrors[detail])
  return `${t('requestFailed')} (HTTP ${status})`
}

export function formatDateTime(value) {
  const date = value instanceof Date ? value : new Date(value)
  if (Number.isNaN(date.getTime())) return ''
  return new Intl.DateTimeFormat(DEFAULT_LOCALE, {
    dateStyle: 'medium',
    timeStyle: 'short',
    timeZone: 'Asia/Seoul',
  }).format(date)
}
